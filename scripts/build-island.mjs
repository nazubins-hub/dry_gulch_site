#!/usr/bin/env node
//
// Generate the mountable plant browser from the database's UI template plus the
// GATED dataset.
//
//   node scripts/build-island.mjs
//
// The database owns the interface; this repo owns what may be said publicly.
// Keeping those separate is the whole point: the template arrives verbatim with a
// /* __PLANTS__ */ placeholder, and the only thing injected is data that has been
// through publish-gate.js. Nothing here decides what is publishable, and nothing
// in the template holds a copy of a species fact.
//
// Output is a build product — gitignored, regenerated before every dev run and
// build, never edited by hand.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ISLAND_OUT, PUBLIC_DATA, SITE_ROOT } from './plant-db-common.mjs';
import { gateAll, withheldCounts } from '../src/lib/publish-gate.js';

const TEMPLATE = join(SITE_ROOT, 'src/components/XericPlantDB.template.jsx');
const PLACEHOLDER = '/* __PLANTS__ */';

const template = readFileSync(TEMPLATE, 'utf8');

if (!template.includes(PLACEHOLDER)) {
  console.error(`  template is missing the ${PLACEHOLDER} placeholder.`);
  console.error('  the database changed its template contract — re-check render_jsx.py.');
  process.exit(1);
}

// Gated at sync time. This file is the only species data in the repo.
const gated = JSON.parse(readFileSync(join(SITE_ROOT, PUBLIC_DATA), 'utf8'));

// A withheld rating must arrive as null, not as a number the UI could render.
// hiz() maps null to its "unrated" branch; anything else would state a rating.
const leaked = gated.filter((p) => p.ignWithheld && p.ign !== null);
const srcLeaked = gated.filter((p) => p.ignSrc === 'est');
if (leaked.length || srcLeaked.length) {
  console.error(`  gate failure: ${leaked.length} withheld rating(s) carry a value,`);
  console.error(`                ${srcLeaked.length} record(s) still marked ignSrc "est"`);
  process.exit(1);
}

// The gate must be idempotent: re-applying it to already-gated data has to be a
// no-op. If it is not, the withheld flags are derived from evidence that has already
// been removed, and a second pass silently forgets that anything was withheld.
const before = JSON.stringify(withheldCounts(gated));
const after = JSON.stringify(withheldCounts(gateAll(gated)));
if (before !== after) {
  console.error('  gate is not idempotent — re-gating changed the withheld counts:');
  console.error(`    once: ${before}   twice: ${after}`);
  console.error('  see the IDEMPOTENT note in src/lib/publish-gate.js');
  process.exit(1);
}

// The component ships its own Google Fonts @import for standalone use. On this site
// the host page already serves those families from /fonts, so the import is stripped
// here rather than removed upstream — the database's own standalone view still needs
// it. Without this the page would make a third-party request on every visit,
// disclosing visitor IPs to Google and forcing the CSP to allow an external origin.
const FONT_IMPORT = /^\s*@import url\(['"]https:\/\/fonts\.googleapis\.com[^)]*\);?\s*$/m;

if (!FONT_IMPORT.test(template)) {
  console.error('  expected a Google Fonts @import in the UI template, found none.');
  console.error('  either it moved (adjust the pattern) or it is already gone.');
  console.error('  refusing to build blind — a silent miss would reintroduce a');
  console.error('  third-party request and break the CSP.');
  process.exit(1);
}

const deFonted = template.replace(
  FONT_IMPORT,
  '\n        /* Google Fonts @import removed by build-island.mjs — the host page\n' +
    '           serves these families from /fonts. See src/styles/fonts.css. */\n',
);

const banner = `/* GENERATED by scripts/build-island.mjs — do not edit.
   UI from the plant database's ui/template.jsx; data gated by src/lib/publish-gate.js.
   ${gated.filter((p) => p.ign !== null).length} of ${gated.length} species carry a published fire rating. */`;

const out = deFonted.replace(
  PLACEHOLDER,
  `${banner}\nconst PLANTS = ${JSON.stringify(gated)};`,
);

writeFileSync(join(SITE_ROOT, ISLAND_OUT), out);

const counts = withheldCounts(gated);
console.log(
  `  built ${ISLAND_OUT} — ${gated.length} species, ${counts.ign} ratings withheld, ${counts.culture} cultural notes withheld`,
);
